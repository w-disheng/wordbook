// A small local bundle lets the dictionary UI also open from a file URL.
// Source modules remain separate for readability and unit tests.
import { readFile, writeFile } from 'node:fs/promises';
const files = ['lib.js', 'dictionary.js', 'learning.js', 'app.js'];
const parts = [];
for (const name of files) {
  const source = await readFile(new URL(`./dist/${name}`, import.meta.url), 'utf8');
  parts.push(`// ${name}\n${source.replace(/^import .*;\s*$/gm, '').replace(/^export /gm, '')}`);
}
await writeFile(new URL('./dist/app.bundle.js', import.meta.url), `// Generated by build.mjs. Edit source modules, then rebuild.\n(() => {\n'use strict';\n${parts.join('\n')}\n})();\n`);
console.log('Built dist/app.bundle.js');
